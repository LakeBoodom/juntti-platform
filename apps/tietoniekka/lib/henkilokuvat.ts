/** Commons-tiedoston nimi URL:sta (thumb- tai alkuperäinen polku), välilyönnein. */
function commonsNimi(url: string): string | null {
  const m = url.match(/\/commons\/(?:thumb\/)?[0-9a-f]\/[0-9a-f]{2}\/([^/?#]+)/);
  if (!m) return null;
  try {
    return decodeURIComponent(m[1]).replace(/_/g, " ");
  } catch {
    return m[1].replace(/_/g, " ");
  }
}

/** Henkilökuvan oma kopio tai null. Paikalliset polut (/20/...) kelpaavat sellaisenaan. */
export function henkiloKuva(url: string | null | undefined): string | null {
  if (!url) return null;
  if (url.startsWith("/")) return url;
  const nimi = commonsNimi(url);
  return (nimi && HENKILOKUVAT[nimi]) || null;
}
